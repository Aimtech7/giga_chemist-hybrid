// Bundles the online API (server/online/vercel-entry.ts) into api/index.js for Vercel.
// npm packages stay external (Vercel installs them); only project source is bundled, so the
// extensionless ESM imports used across server/ work in the Vercel Node runtime.
//   node scripts/build-online-api.mjs          write api/index.js
//   node scripts/build-online-api.mjs --check  exit 1 if the committed bundle is stale
import fs from 'fs';
import { build } from 'esbuild';

const out = 'api/index.js';
const result = await build({
  entryPoints: ['server/online/vercel-entry.ts'],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  packages: 'external',
  write: false,
  legalComments: 'none',
  banner: { js: '// GENERATED by scripts/build-online-api.mjs from server/online/vercel-entry.ts — do not edit. Run: npm run build:api' },
});
const code = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf-8') : '';
  if (current !== code) {
    console.error(`${out} is stale: run "npm run build:api" and commit it.`);
    process.exit(1);
  }
  console.log(`${out} is up to date.`);
} else {
  fs.mkdirSync('api', { recursive: true });
  fs.writeFileSync(out, code);
  console.log(`wrote ${out} (${(code.length / 1024).toFixed(0)} KB)`);
}
